"""Synthetic-only, versioned withdrawal sidecar proposal; pure in-memory adapter.

The JSON payload below is an invented code-generated test format, not a known
producer representation. Hashes check internal integrity, not authenticity or
comprehensive public collection. No real ingestion or readiness is implemented.
"""

from __future__ import annotations

import json
from copy import deepcopy
from datetime import date
from typing import Any

from modeler.feedback.core import FeedbackError, canonical_bytes, require_hash, sha256_bytes
from modeler.feedback_outcomes.contracts import BUNDLE_SHA256, MODEL_ID, MODEL_VERSION, stamp

SCHEMA = "kr-v1-synthetic-withdrawal-sidecar-proposal.v1"
PAYLOAD_SCHEMA = "codegen-synthetic-withdrawal-unit.v1"
MAX_RECORDS = 256
MAX_EVIDENCE_BYTES = 1024 * 1024
BINDING_KEYS = (
    "publication_ref",
    "report_sha256",
    "invocation_id",
    "market",
    "model_id",
    "model_version",
    "bundle_hash",
    "input_sha256",
    "feature_asof_date",
    "report_date",
    "decision_at",
)


def _shape(value: Any, keys: set[str], name: str) -> dict:
    if not isinstance(value, dict) or set(value) != keys:
        raise FeedbackError(f"invalid {name} schema")
    return value


def _binding(value: Any) -> dict:
    value = _shape(value, set(BINDING_KEYS), "original binding")
    for key in ("publication_ref", "report_sha256", "bundle_hash", "input_sha256"):
        require_hash(value[key])
    if (value["market"], value["model_id"], value["model_version"], value["bundle_hash"]) != (
        "KR",
        MODEL_ID,
        MODEL_VERSION,
        BUNDLE_SHA256,
    ):
        raise FeedbackError("original binding is outside the sealed KR model")
    if not isinstance(value["invocation_id"], str) or not value["invocation_id"].strip():
        raise FeedbackError("invalid original invocation")
    for key in ("feature_asof_date", "report_date"):
        try:
            valid = (
                isinstance(value[key], str)
                and date.fromisoformat(value[key]).isoformat() == value[key]
            )
        except ValueError:
            valid = False
        if not valid:
            raise FeedbackError("invalid original binding date")
    stamp(value["decision_at"])
    return value


def _unique_object(pairs: list[tuple[str, Any]]) -> dict:
    result = {}
    for key, value in pairs:
        if key in result:
            raise FeedbackError("duplicate withdrawal payload key")
        result[key] = value
    return result


def _payload(raw: bytes) -> dict:
    try:
        value = json.loads(raw, object_pairs_hook=_unique_object)
    except (ValueError, UnicodeError) as exc:
        raise FeedbackError("invalid withdrawal evidence JSON") from exc
    value = _shape(
        value,
        {
            "schema",
            "synthetic_fixture",
            "declaration",
            "original_binding",
            "revision",
            "reports_commit",
        },
        "withdrawal payload",
    )
    if (
        value["schema"] != PAYLOAD_SCHEMA
        or value["synthetic_fixture"] is not True
        or value["declaration"] != "withdrawal"
    ):
        raise FeedbackError("explicit synthetic withdrawal declaration required")
    _binding(value["original_binding"])
    if type(value["revision"]) is not int or value["revision"] <= 0:
        raise FeedbackError("invalid withdrawal payload revision")
    return value


def normalize_withdrawals(
    sidecar: dict,
    original_publications: list[dict],
    *,
    observed_at: str,
    synthetic: bool = False,
) -> list[dict]:
    """Adapt explicit code-generated byte evidence for ``select_cohorts`` tests.

    ``synthetic=True`` and both fixture flags are mandatory. The real-mode guard
    runs before parsing or hashing anything, including malformed byte evidence.
    Empty output makes no assertion that a real withdrawal was absent. This API
    performs no I/O and must never authorize real source or outcome access.
    """
    if synthetic is not True:
        raise FeedbackError("withdrawal sidecar proposal is synthetic-only")
    if not isinstance(sidecar, dict) or sidecar.get("synthetic_fixture") is not True:
        raise FeedbackError("synthetic withdrawal sidecar fixture flag required")
    if not isinstance(original_publications, list) or any(
        not isinstance(event, dict)
        or event.get("kind") != "publication"
        or event.get("synthetic_fixture") is not True
        or event.get("historical_replay") is not False
        for event in original_publications
    ):
        raise FeedbackError("original publications must be explicit synthetic fixtures")

    _shape(
        sidecar,
        {
            "schema",
            "synthetic_fixture",
            "coverage",
            "records",
            "head_ref",
            "evidence",
            "sidecar_ref",
        },
        "withdrawal sidecar",
    )
    if sidecar["schema"] != SCHEMA:
        raise FeedbackError("unsupported withdrawal sidecar proposal version")
    cutoff = stamp(observed_at)
    coverage = _shape(sidecar["coverage"], {"started_at", "through", "status", "gaps"}, "coverage")
    started, through = stamp(coverage["started_at"]), stamp(coverage["through"])
    if coverage["status"] != "covered" or coverage["gaps"] != []:
        raise FeedbackError("withdrawal sidecar coverage gap")
    if started > through or through != cutoff:
        raise FeedbackError("withdrawal coverage must span baseline through observation cutoff")
    records, evidence = sidecar["records"], sidecar["evidence"]
    if not isinstance(records, list) or not 1 <= len(records) <= MAX_RECORDS:
        raise FeedbackError("withdrawal sidecar requires a bounded baseline chain")
    if (
        not isinstance(evidence, dict)
        or len(evidence) >= MAX_RECORDS
        or any(type(raw) is not bytes for raw in evidence.values())
    ):
        raise FeedbackError("withdrawal evidence must be in-memory code-generated bytes")
    for digest in evidence:
        require_hash(digest)
    if sum(map(len, evidence.values())) > MAX_EVIDENCE_BYTES:
        raise FeedbackError("withdrawal evidence exceeds the synthetic metadata cap")
    envelope = {
        key: value for key, value in sidecar.items() if key not in {"sidecar_ref", "evidence"}
    }
    envelope_bytes = canonical_bytes(envelope)
    if len(envelope_bytes) > MAX_EVIDENCE_BYTES:
        raise FeedbackError("withdrawal sidecar metadata exceeds the synthetic metadata cap")
    if require_hash(sidecar["sidecar_ref"]) != sha256_bytes(envelope_bytes):
        raise FeedbackError("withdrawal sidecar hash mismatch")

    originals = {}
    for original in original_publications:
        binding = _binding({key: original.get(key) for key in BINDING_KEYS})
        ref = binding["publication_ref"]
        if ref in originals:
            raise FeedbackError("duplicate original publication reference")
        original_at = stamp(original.get("verified_by"))
        if original_at > cutoff:
            raise FeedbackError("original publication is after observation cutoff")
        if started > original_at:
            raise FeedbackError("withdrawal coverage starts after original publication observation")
        originals[ref] = (binding, original_at)

    output, used_sources, seen_refs = [], set(), set()
    previous, previous_at, previous_verified = None, started, started
    for sequence, record in enumerate(records):
        common = {"kind", "sequence", "previous_ref", "observed_at", "record_ref"}
        _shape(
            record,
            common if sequence == 0 else common | {"source_sha256", "receipt", "receipt_ref"},
            "withdrawal chain record",
        )
        ref = require_hash(record["record_ref"])
        if ref in seen_refs:
            raise FeedbackError("duplicate withdrawal record reference")
        seen_refs.add(ref)
        body = {key: value for key, value in record.items() if key != "record_ref"}
        if sha256_bytes(canonical_bytes(body)) != ref:
            raise FeedbackError("withdrawal record hash mismatch")
        if (
            type(record["sequence"]) is not int
            or record["sequence"] != sequence
            or record["previous_ref"] != previous
            or record["kind"] != ("baseline" if sequence == 0 else "withdrawal_evidence")
        ):
            raise FeedbackError("withdrawal chain discontinuity or unsupported event")
        observed = stamp(record["observed_at"])
        if not previous_at <= observed <= through:
            raise FeedbackError("withdrawal observation is unordered or after cutoff")
        if sequence == 0:
            if observed != started:
                raise FeedbackError("withdrawal baseline does not match collection start")
        else:
            receipt = _shape(
                record["receipt"],
                {
                    "verified_by",
                    "remote_verified",
                    "revision",
                    "reports_commit",
                    "unit_sha256",
                    "original_binding",
                },
                "withdrawal receipt",
            )
            receipt_ref = require_hash(record["receipt_ref"])
            if sha256_bytes(canonical_bytes(receipt)) != receipt_ref:
                raise FeedbackError("withdrawal receipt hash mismatch")
            verified = stamp(receipt["verified_by"])
            if (
                receipt["remote_verified"] is not True
                or not previous_verified <= verified <= observed
            ):
                raise FeedbackError("withdrawal requires ordered remote verified observation")
            previous_verified = verified
            if type(receipt["revision"]) is not int or receipt["revision"] <= 0:
                raise FeedbackError("invalid withdrawal revision")
            require_hash(receipt["reports_commit"], length=40)
            digest = require_hash(record["source_sha256"])
            if digest in used_sources:
                raise FeedbackError("duplicate withdrawal source evidence")
            used_sources.add(digest)
            if digest not in evidence or sha256_bytes(evidence[digest]) != digest:
                raise FeedbackError("withdrawal evidence byte hash mismatch")
            if require_hash(receipt["unit_sha256"]) != digest:
                raise FeedbackError("withdrawal unit hash mismatch")
            payload = _payload(evidence[digest])
            binding = _binding(receipt["original_binding"])
            if payload["original_binding"] != binding or any(
                payload[key] != receipt[key] for key in ("revision", "reports_commit")
            ):
                raise FeedbackError("withdrawal source and receipt binding mismatch")
            original = originals.get(binding["publication_ref"])
            if original is None or original[0] != binding:
                raise FeedbackError("withdrawal original publication binding mismatch")
            if verified < original[1]:
                raise FeedbackError("withdrawal before original publication observation")
            output.append(
                {
                    **deepcopy(binding),
                    "kind": "withdrawal",
                    "original_publication_ref": binding["publication_ref"],
                    "original_report_sha256": binding["report_sha256"],
                    "publication_ref": ref,
                    "receipt_ref": receipt_ref,
                    "reports_commit": receipt["reports_commit"],
                    "unit_sha256": digest,
                    "revision": receipt["revision"],
                    "verified_by": receipt["verified_by"],
                    "collection_started_at": coverage["started_at"],
                    "coverage_status": "covered",
                    "synthetic_fixture": True,
                    "historical_replay": False,
                    "explicit_withdrawal_adapter": "synthetic_sidecar_proposal",
                    "withdrawal_sidecar_ref": sidecar["sidecar_ref"],
                    "withdrawal_evidence_sha256": digest,
                    "absence_claim": "none",
                }
            )
        previous, previous_at = ref, observed
    if require_hash(sidecar["head_ref"]) != previous:
        raise FeedbackError("withdrawal chain head mismatch")
    if set(evidence) != used_sources:
        raise FeedbackError("withdrawal source evidence inventory mismatch")
    return output
